"""Two real signed Apps and a local relay; all files/tmux remain disposable."""

import json
from pathlib import Path
import socket
import subprocess
import sys
import time
import traceback
import uuid

PHASE, HOST, VIEWER, SOCKET = sys.argv[1], Path(sys.argv[2]).resolve(), Path(sys.argv[3]).resolve(), sys.argv[4]
assert Path(SOCKET).name.startswith("cx-workspace-viewer-") and HOST.parent == VIEWER.parent
EVIDENCE = HOST.parent / "evidence"
PROJECT = HOST / "viewer-project"
DRAFT = "Unsent Viewer recovery prompt: inspect the remote file, do not execute anything."
EVIDENCE.mkdir(parents=True, exist_ok=True)


def tmux(*args):
    return subprocess.check_output(["tmux", "-f", "/dev/null", "-S", SOCKET, *args], text=True, timeout=10).rstrip("\n")


def save(name, value):
    path = EVIDENCE / (name + ".json")
    temporary = path.with_suffix(".tmp")
    temporary.write_text(json.dumps(value, indent=2) + "\n")
    temporary.replace(path)


def snapshot(root):
    return json.loads((root / "Recovery/workspace.json").read_text())


def wait(check):
    deadline = time.monotonic() + 35
    while True:
        try:
            return check()
        except (AssertionError, FileNotFoundError, KeyError, StopIteration, json.JSONDecodeError) as error:
            if time.monotonic() >= deadline:
                raise AssertionError(f"{PHASE}: {error}") from error
            time.sleep(0.2)


def host_session(value):
    return next(s for s in value["sessions"] if s["name"] == "restore-viewer")


def live():
    return tmux("list-panes", "-s", "-t", "restore-viewer", "-F", "#{window_index}|#{pane_id}|#{pane_pid}|#{@ctrlx-recovery-pane}")


def setup():
    # Configure the two disposable installations before either App is running.
    # Pairing keys are still generated by each App and exchanged through the UI.
    for root in [HOST, VIEWER]:
        root.mkdir(parents=True, exist_ok=True, mode=0o700)
        root.chmod(0o700)
        storage = root / "e2e-storage.json"
        assert not storage.exists()
        storage.write_text(json.dumps({
            "preferences": {"autoConnectToServer": {"bool": {"_0": True}}},
            "sessionKeys": {}, "secrets": {},
        }))
        storage.chmod(0o600)
    (PROJECT / "docs/nested").mkdir(parents=True)
    (PROJECT / "docs/chapter.txt").write_text("VIEWER_PRIVATE_PREVIEW\n" + "\n".join(f"remote chapter {n}" for n in range(100)))
    (PROJECT / "docs/nested/detail.txt").write_text("Remote nested preview.\n")
    (HOST / "editor-request.txt").write_text("Original remote prompt must remain unchanged.")
    (HOST / ".workspace-viewer-fixture").touch()
    tmux("respawn-pane", "-k", "-t", "restore-viewer:0", "-c", str(PROJECT), "/bin/sh")
    tmux("rename-window", "-t", "restore-viewer:0", "SOURCE")
    tmux("set-window-option", "-t", "restore-viewer:0", "automatic-rename", "off")
    tmux("new-window", "-d", "-t", "restore-viewer:2", "-n", "DETACHED", "-c", str(PROJECT / "docs"), "/bin/sh")
    tmux("set-window-option", "-t", "restore-viewer:2", "automatic-rename", "off")
    tmux("select-window", "-t", "restore-viewer:0")
    return {"project": str(PROJECT)}


def editor():
    with socket.socket(socket.AF_UNIX, socket.SOCK_STREAM) as client:
        client.settimeout(180)
        client.connect(str(HOST / "api.sock"))
        request = {"id": str(uuid.uuid4()), "method": "editor.open", "params": {"pane_id": tmux("display-message", "-p", "-t", "restore-viewer:0", "#{pane_id}"), "file_path": str(HOST / "editor-request.txt")}}
        client.sendall((json.dumps(request) + "\n").encode())
        response = b""
        while b"\n" not in response:
            block = client.recv(4096)
            if not block:
                break
            response += block
        return {"response": response.decode()}


def require_content():
    host, viewer = snapshot(HOST), snapshot(VIEWER)
    session = host_session(host)
    windows = {w["index"]: w for w in session["windows"]}
    assert set(windows) == {0, 2}, windows
    main = next(s for s in viewer["viewerScenes"] if s["isMain"])
    detached = next(s for s in viewer["viewerScenes"] if not s["isMain"])
    main_item = next(s for s in main["sessions"] if s["sessionName"] == "restore-viewer")
    detached_item = next(s for s in detached["sessions"] if s["sessionName"] == "restore-viewer")
    assert main_item["ownedWindowIDs"] == [windows[0]["id"]], main_item
    assert detached_item["ownedWindowIDs"] == [windows[2]["id"]], detached_item
    reference = main_item["remoteReference"]
    assert reference["hostID"] == host["hostID"] and reference["sessionID"] == session["id"], reference
    assert main["selectedHostID"] == reference["pairID"] and main["selectedSessionID"] == session["id"], main
    assert detached_item["remoteReference"] == reference
    tabs = main_item["layout"]["fileTabs"]
    assert len(tabs) == 1, tabs
    browser = tabs[0]["browser"]
    assert Path(browser["path"]).resolve() == PROJECT / "docs", browser
    assert Path(browser["selectedFile"]).resolve() == PROJECT / "docs/chapter.txt", browser
    assert PROJECT / "docs/nested" in {Path(path).resolve() for path in browser["expanded"]}, browser
    assert len(host["fileTabs"]) == 1 and host["fileTabs"][0]["id"] == tabs[0]["id"], host["fileTabs"]
    for scene in host["scenes"]:
        for item in scene["sessions"]:
            for tab in item["layout"]["fileTabs"]:
                assert tab.get("browser", {}).get("selectedFile") != browser["selectedFile"], "Viewer navigation leaked into Host"
    drafts = [d for d in viewer["drafts"] if d["text"] == DRAFT]
    assert len(drafts) == 1, viewer["drafts"]
    pane = windows[0]["panes"][0]
    expected = dict(reference, windowID=windows[0]["id"], paneID=pane["id"])
    assert drafts[0]["remoteReference"] == expected and drafts[0]["paneID"] == pane["id"], drafts[0]
    assert (HOST / "editor-request.txt").read_text() == "Original remote prompt must remain unchanged."
    assert not host.get("recovery") and not viewer.get("recovery")
    return {"host": host, "viewer": viewer, "live": live(), "reference": reference, "draft": drafts[0]}


def run():
    if PHASE == "setup": return setup()
    assert (HOST / ".workspace-viewer-fixture").exists()
    if PHASE == "autoconnect":
        for root in [HOST, VIEWER]:
            preferences = json.loads((root / "e2e-storage.json").read_text())["preferences"]
            assert preferences["autoConnectToServer"] == {"bool": {"_0": True}}, "Auto-connect was not enabled in Settings"
        return {"hostAndViewerAutoConnect": True}
    if PHASE == "editor": return editor()
    if PHASE in ["captured", "restored", "host-offline", "rebuilt", "relaunch"]:
        result = wait(require_content)
        if PHASE == "captured":
            save("baseline", result)
        else:
            before = json.loads((EVIDENCE / "baseline.json").read_text())
            assert result["reference"] == before["reference"] and result["draft"] == before["draft"]
            assert result["host"]["fileTabs"] == before["host"]["fileTabs"]
            for saved in before["viewer"]["viewerScenes"]:
                current = next(s for s in result["viewer"]["viewerScenes"] if s["id"] == saved["id"])
                assert current.get("selectedSessionID") == saved.get("selectedSessionID")
                old_frame = [v for pair in saved["frame"] for v in pair]
                new_frame = [v for pair in current["frame"] for v in pair]
                assert len(old_frame) == len(new_frame) == 4
                assert all(abs(a - b) <= 2 for a, b in zip(old_frame, new_frame)), (old_frame, new_frame)
                for item in saved["sessions"]:
                    restored = next(s for s in current["sessions"] if s["remoteReference"] == item["remoteReference"])
                    assert restored["layout"]["tabOrder"] == item["layout"]["tabOrder"], "Viewer tab order changed"
                    assert restored.get("selectedWindowID") == item.get("selectedWindowID"), "Viewer terminal selection changed"
                    for field in ["rightSide", "selectedLeft", "selectedRight", "splitRatio"]:
                        assert restored["layout"].get(field) == item["layout"].get(field), (field, restored["layout"], item["layout"])
                    assert restored["focusedRight"] == item["focusedRight"]
            if PHASE == "restored":
                assert result["live"] == before["live"], "App relaunch restarted a Host process"
            elif PHASE == "rebuilt":
                assert result["live"] != before["live"]
                assert result["host"]["serverID"] != before["host"]["serverID"]
                old = {p["runtimeID"] for w in host_session(before["host"])["windows"] for p in w["panes"]}
                new = {p["runtimeID"] for w in host_session(result["host"])["windows"] for p in w["panes"]}
                assert old != new
            elif PHASE == "relaunch":
                assert result["live"] == json.loads((EVIDENCE / "rebuilt.json").read_text())["live"], "Viewer relaunch recreated a Host process"
        return result
    if PHASE == "offline":
        before = json.loads((EVIDENCE / "baseline.json").read_text())
        value = snapshot(VIEWER)
        assert before["draft"] in value["drafts"]
        assert value["viewerScenes"] == before["viewer"]["viewerScenes"], "Offline launch discarded the private workspace"
        return {"viewer": value}
    if PHASE == "prepare-reboot":
        value = snapshot(HOST)
        value["bootID"] = "workspace-viewer-simulated-boot"
        (HOST / "Recovery/workspace.json").write_text(json.dumps(value))
        return {"simulatedBootChange": True}
    if PHASE == "input":
        source = tmux("capture-pane", "-p", "-t", "restore-viewer:0")
        other = tmux("capture-pane", "-p", "-t", "restore-viewer:2")
        assert "VIEWER_RECOVERY_INPUT" in source.splitlines(), source
        assert "VIEWER_RECOVERY_INPUT" not in other, other
        return {"routedToRebuiltSource": True}
    raise ValueError(PHASE)


try:
    result = run()
    save(PHASE, {"passed": True, **result})
except Exception:
    save(PHASE, {"passed": False, "error": traceback.format_exc()})
    for name, root in [("host", HOST), ("viewer", VIEWER)]:
        journal = root / "Recovery/workspace.json"
        if journal.exists():
            (EVIDENCE / (PHASE + "-" + name + "-journal.json")).write_bytes(journal.read_bytes())
    raise
